def strong_password(n: int = 20) -> str:
    alphabet = "abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"  # letters+digits: safe in URLs
    while True:
        p = "".join(_secrets.choice(alphabet) for _ in range(n))
        if any(c.isdigit() for c in p) and any(c.isalpha() for c in p):
            return p


