def say(msg: str = "", kind: str = "") -> None:
    icon = {"ok": "[ OK ]", "warn": "[WARN]", "bad": "[FAIL]", "step": "==>"}.get(kind, "")
    print(f"{icon} {msg}" if icon else msg, flush=True)


def venv_python() -> Path:
    return VENV / ("Scripts/python.exe" if os.name == "nt" else "bin/python")


def in_venv() -> bool:
    return Path(sys.prefix).resolve() == VENV.resolve()


def reexec_in_venv(argv: List[str]) -> None:
    """Commands that need the app's packages run with the project's .venv Python."""
    if in_venv():
        return
    py = venv_python()
    if not py.exists():
        say("The project environment does not exist yet. Run:  python launch.py setup", "bad")
        sys.exit(1)
    sys.exit(subprocess.call([str(py), str(ROOT / "launch.py"), *argv]))


def parse_env(text: str) -> Dict[str, str]:
    """Minimal .env parser: KEY=value, '#' comments, optional quotes. 'KEY=   # note' means empty."""
    out: Dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        key, val = key.strip(), val.strip()
        if val[:1] in ("'", '"') and val.count(val[0]) >= 2:
            val = val[1:val.index(val[0], 1)]
        else:
            val = re.split(r"\s+#", " " + val, maxsplit=1)[0].strip() if val else ""
            if val.startswith("#"):
                val = ""
        if re.match(r"^[A-Z][A-Z0-9_]*$", key):
            out[key] = val
    return out


def toml_value(v: str) -> str:
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def env_to_toml(env: Dict[str, str]) -> Tuple[str, List[str]]:
    """Streamlit Cloud secrets (flat TOML) + warnings. Empty values are skipped; local-only settings dropped."""
    local_only = {"DATA_DIR", "OLLAMA_BASE_URL", "OLLAMA_MODEL", "OLLAMA_FAST_MODEL", "OLLAMA_VISION_MODEL",
                  "POSTGRES_PASSWORD", "MINIO_ROOT_USER", "MINIO_ROOT_PASSWORD", "GRAFANA_ADMIN_PASSWORD", "DOMAIN"}
    warnings: List[str] = []
    lines = ["# Streamlit Community Cloud → your app → ⋮ → Settings → Secrets. Paste this, then Save.",
             "# Generated by `python launch.py secrets`. Contains secrets: never commit or share it.", ""]
    for k, v in env.items():
        if v == "" or k in local_only:
            continue
        lines.append(f"{k} = {toml_value(v)}")
    if env.get("AUTH_MODE", "none") != "users":
        warnings.append("AUTH_MODE is not 'users': anyone with the link could use the app. Set AUTH_MODE=users "
                        "plus ADMIN_USERNAME / ADMIN_PASSWORD in .env and run this again.")
    db = env.get("DATABASE_URL", "")
    if not db or db.startswith("sqlite") or "localhost" in db or "127.0.0.1" in db:
        warnings.append("DATABASE_URL is empty or local: Streamlit Cloud cannot reach it and its disk is wiped on "
                        "restart. Use a hosted PostgreSQL URL (e.g. Neon, with ?sslmode=require).")
    if not (env.get("HF_TOKEN") and env.get("HF_DATASET_REPO")):
        warnings.append("HF_TOKEN / HF_DATASET_REPO are empty: uploaded documents' search indexes are lost when "
                        "the Cloud app restarts (accounts and chats in PostgreSQL are kept).")
    if not env.get("GROQ_API_KEY"):
        warnings.append("GROQ_API_KEY is empty: no written answers.")
    if env.get("LLM_MODE", "hybrid") == "local":
        warnings.append("LLM_MODE=local cannot work on Streamlit Cloud (no Ollama there). Use hybrid or cloud.")
    return "\n".join(lines) + "\n", warnings


