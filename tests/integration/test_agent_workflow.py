def _run(settings, index, q, **kw):
    return AgentWorkflow(settings).run(q, [index], ModelRouter(settings), AskRequest(q, [index], **kw))


def test_task_classification(make_settings):
    u = QueryUnderstandingAgent()
    s = make_settings()
    assert u.run("Summarize this document", None, 1, s).task == "summarization"
    assert u.run("Calculate the power dissipation at 12 V and 1.5 A", None, 1, s).task == "calculation"
    assert u.run("What does Figure 2 show?", None, 1, s).task == "figure"
    assert u.run("Compare the min and max output voltage", None, 1, s).task == "comparison"
    assert u.run("What is the dropout voltage?", None, 1, s).task == "question"
    assert u.run("hello!", None, 1, s).task == "greeting"


def test_full_trace_for_a_question(indexed, server):
    index, s = indexed
    res = _run(s, index, "What is the peak output current?")
    agents = [t["agent"] for t in res.agent_trace]
    assert agents == ["Query Understanding Agent", "Document Retrieval Agent", "Reasoning Agent",
                      "Citation Verification Agent", "Answer Quality Agent"]
    assert all(t["status"] == "ok" for t in res.agent_trace) and res.kind == "answer"
    assert res.plan["task"] == "question" and "quality_score" in res.metrics
    assert not any("2.2 A" in t["summary"] for t in res.agent_trace)  # trace never carries document text


def test_summarization_agent_uses_whole_document(indexed, server):
    index, s = indexed
    res = _run(s, index, "Summarize this document")
    assert [t["agent"] for t in res.agent_trace][1] == "Summarization Agent"
    pages = {src.page for src in res.sources}
    assert res.kind == "answer" and len(res.retrieval_debug["selected"]) >= 4
    assert {e["page"] for e in res.retrieval_debug["selected"]} >= {1, 2, 3, 4} or len(pages) >= 1


def test_greeting_and_no_documents_skip_llm(make_settings, server):
    s = make_settings()
    r = AgentWorkflow(s).run("hi", [], ModelRouter(s), AskRequest("hi", []))
    assert r.kind == "answer" and not r.used_llm
    r = AgentWorkflow(s).run("What is VOUT?", [], ModelRouter(s), AskRequest("What is VOUT?", []))
    assert r.kind == "not_found" and "Upload" in r.answer
    assert not [x for x in server_log(server)["requests"] if x[0] in ("groq", "chat")]


def test_reasoning_timeout_falls_back(indexed, server, monkeypatch, make_settings):
    index, _ = indexed
    s = make_settings(agent_timeout_s=5.0)

    def slow(*a, **kw):
        time.sleep(7)
        return QueryResult("answer", "late")
    monkeypatch.setattr(wf, "answer_pro", slow)
    t0 = time.perf_counter()
    r = _run(s, index, "What is the dropout voltage?")
    assert time.perf_counter() - t0 < 6.5 and r.kind == "not_found" and "too long" in r.warnings[0]
    assert r.agent_trace[-1]["status"] == "timeout"


def test_reasoning_failure_returns_evidence(indexed, server):
    index, s = indexed
    control(server, "all")
    r = _run(s, index, "What is the dropout voltage?")
    reasoning = next(t for t in r.agent_trace if t["agent"] == "Reasoning Agent")
    assert reasoning["status"] == "fallback" and r.sources and not r.used_llm


def test_quality_agent_abstains_on_unsupported_claims(make_settings):
    q = AnswerQualityAgent()
    bad = QueryResult("answer", "x", used_llm=True, sources=[object()],
                      verification={"verdict": "failed", "grounded": False, "unsupported_claims": ["9.87 A"]})
    assert q.run(bad, make_settings())["action"] == "abstain"
    assert q.run(bad, make_settings(abstain_ungrounded=False))["action"] == "warn"
    good = QueryResult("answer", "x", used_llm=True, sources=[object()], metrics={"answer_relevance": 0.6},
                       verification={"verdict": "verified", "grounded": True})
    assert q.run(good, make_settings()) == {"action": "accept", "score": 1.0, "issues": []}


def test_unsupported_number_is_corrected_or_withheld(indexed, server):
    index, s = indexed
    r = _run(s, index, "What is the unsupported number for output current?")
    assert "9.87" not in r.answer  # regenerated by the verifier loop, or withheld by the quality agent
